## Operators in Python

"""
Types of Operators in Python

1. Arithmetic Operators : +, -, *, /, %, **, //
2. Comparison Operators : ==, !=, >, <, >=, <=
3. Assignment Operators : =, +=, -=, *=, /=, %=, **=, //=
4. Logical Operators : and, or, not
5. Bitwise Operators : &, |, ^, ~, <<, >>
"""

"""
1. Arithmetic Operators

+ : Addition
- : Subtraction
* : Multiplication
/ : Division
% : Modulus (Remainder)
** : Exponentiation (Power)
// : Floor Division (Quotient without remainder)

"""

"""
2. Comparison Operators

== : Equal to
!= : Not equal to
> : Greater than
< : Less than
>= : Greater than or equal to
<= : Less than or equal to

"""

"""
3. Assignment Operators

= : Assign value
+= : Add and assign
-= : Subtract and assign
*= : Multiply and assign
/= : Divide and assign
%= : Modulus and assign
**= : Exponentiation and assign
//= : Floor division and assign

name = "sonal"
name += " anand" # name = name - " anand"
print(name)

age = 25
age -= 1 # age = age - 1
print(age)

"""

"""
4. Logical Operators

and : Returns True if both statements are true
or : Returns True if one of the statements is true
not : Returns True if the statement is false

"""

"""
5. Bitwise Operators

& : Bitwise AND
| : Bitwise OR
^ : Bitwise XOR
~ : Bitwise NOT
<< : Bitwise left shift
>> : Bitwise right shift

0 - 0
1 - 1
2 - 10
3 - 11
"""








